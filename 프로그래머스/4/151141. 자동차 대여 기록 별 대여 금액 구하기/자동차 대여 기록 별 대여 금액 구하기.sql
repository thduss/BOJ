# 트럭인 자동차의 대여기록 -> 대여 금액
# 대여금액 기준으로 내림차순 정렬, 기록 ID 내림차순 정렬

SELECT A.HISTORY_ID, (DATEDIFF(A.END_DATE, A.START_DATE)+1)*B.DAILY_FEE*(100-IFNULL(C.DISCOUNT_RATE,0))/100 AS FEE
FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY A 
LEFT JOIN CAR_RENTAL_COMPANY_CAR B ON A.CAR_ID = B.CAR_ID
LEFT JOIN CAR_RENTAL_COMPANY_DISCOUNT_PLAN C ON B.CAR_TYPE = C.CAR_TYPE 
    AND DURATION_TYPE = 
    CASE WHEN DATEDIFF(A.END_DATE, A.START_DATE)+1>=90 THEN '90일 이상'
         WHEN DATEDIFF(A.END_DATE, A.START_DATE)+1>=30 THEN '30일 이상'
         WHEN DATEDIFF(A.END_DATE, A.START_DATE)+1>=7 THEN '7일 이상' END
WHERE B.CAR_TYPE='트럭'
ORDER BY FEE DESC, HISTORY_ID DESC;