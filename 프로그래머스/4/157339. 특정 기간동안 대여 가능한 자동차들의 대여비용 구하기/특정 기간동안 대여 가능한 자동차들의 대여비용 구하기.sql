# 세단, suv인 자동차 && 2022-11-01 ~ 2022-11-30 대여 가능 && 50만원<=대여 금액<200만원

SELECT A.CAR_ID, A.CAR_TYPE, A.DAILY_FEE*30*(1-B.DISCOUNT_RATE*0.01) AS FEE
FROM CAR_RENTAL_COMPANY_CAR A
LEFT JOIN (SELECT * FROM CAR_RENTAL_COMPANY_DISCOUNT_PLAN WHERE DURATION_TYPE='30일 이상') B 
    ON A.CAR_TYPE = B.CAR_TYPE
WHERE A.CAR_TYPE IN ('세단', 'SUV') 
    AND A.CAR_ID NOT IN (SELECT CAR_ID 
                           FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY
                         WHERE (DATE_FORMAT(START_DATE,'%Y-%m')='2022-11') OR 
                               (DATE_FORMAT(END_DATE,'%Y-%m')='2022-11') OR 
                               (DATE_FORMAT(START_DATE,'%Y-%m')<'2022-11' AND DATE_FORMAT(END_DATE, '%Y-%m')>='2022-11'))
    AND A.DAILY_FEE*30*(1-B.DISCOUNT_RATE*0.01) >= 500000 
    AND A.DAILY_FEE*30*(1-B.DISCOUNT_RATE*0.01) < 2000000
ORDER BY FEE DESC, CAR_TYPE, CAR_ID DESC;