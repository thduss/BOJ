# '세단', 'SUV'
# 2022-11-01 ~ 2022-11-30 대여 가능
# 50 <= 금액 < 200
# 대여금액 기준 내림차순

SELECT A.CAR_ID, A.CAR_TYPE, (30*A.DAILY_FEE*0.01*(100-B.DISCOUNT_RATE)) AS FEE
FROM CAR_RENTAL_COMPANY_CAR A
LEFT JOIN (SELECT * FROM CAR_RENTAL_COMPANY_DISCOUNT_PLAN WHERE DURATION_TYPE='30일 이상') B ON A.CAR_TYPE = B.CAR_TYPE
WHERE A.CAR_TYPE IN ('세단', 'SUV') 
      AND A.CAR_ID NOT IN (SELECT CAR_ID
                             FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY
                            WHERE MONTH(START_DATE)=11 OR MONTH(END_DATE)=11 
                                  OR (START_DATE<='2022-11-01' AND END_DATE>='2022-11-30'))
      AND (30*A.DAILY_FEE*0.01*(100-B.DISCOUNT_RATE))>=500000 AND (30*A.DAILY_FEE*0.01*(100-B.DISCOUNT_RATE))<2000000
ORDER BY FEE DESC;